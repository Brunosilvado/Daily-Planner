/* ---- static, reliable schedule logic (no live data required) ---- */
const routines=[
  ['1st–3rd','Budget & cash flow','Review accounts, prior spending, card statements and automatic payments. Fund the budget and choose a savings goal after reserves.','Identify one upcoming expense and its budget category.'],
  ['7th–10th','Assets & maintenance','Review cash reserves, vehicle maintenance, insurance renewals and trading-account records.','Check one renewal or maintenance need.'],
  ['14th–17th','Retirement & investments','Review contributions and allocation; learn one investment topic. Reviewing does not require buying or selling.','Verify one planned contribution.'],
  ['20th–23rd','Family planning','Review next month’s calendar, appointments, an outing, a date night, birthdays and meals.','Identify one family date to coordinate.'],
  ['27th–month-end','Monthly wrap-up','Review progress, upcoming expenses and unfinished work. Choose next month’s priorities.','Choose one priority for next month.']
];
function windowIndex(day){return day>=27?4:day>=20?3:day>=14?2:day>=7?1:0;}

/* Known, verified calendar exceptions — update only when a real exception is confirmed */
const dateExceptions={
  '2026-10-13':['Keep the evening for Claudia','Your household block is skipped for her birthday.','Protected family evening','No extra task','Rest — no catch-up required.','Calendar exception']
};

function plan(d){
  const key=d.toISOString().slice(0,10), w=d.getUTCDay(), r=routines[windowIndex(d.getUTCDate())];
  if(dateExceptions[key]) return dateExceptions[key];
  if(w===2) return [r[1], 'Choose one step: '+r[2], '8:00–8:30 p.m.', '30 min max', r[3]+' About 5–10 minutes.', 'Household Routines'];
  if(w===3) return ['Study one trading lesson','5 min: choose your next step. 25 min: one lesson or historical example. 5 min: record your takeaway.','8:00–8:35 p.m.','35 min max','Review one historical example and write one takeaway. About 10 minutes.','Trading Development'];
  if(w===4) return ['Replay one setup & journal','Use historical replay or simulation. Check the setup against your rules and record one takeaway. No live-trading instruction.','8:00–8:35 p.m.','35 min max','Review one chart against your rules and write one note. About 10 minutes.','Trading Development'];
  return [w===1?'Childcare comes first':w===5?'An evening together':'Keep space for family','No extra task is scheduled by this routine. Check Calendar for real appointments; leave room for interruptions.','No added evening block','Protected time','Rest. No catch-up session is required.','Standing family priorities'];
}

/* ---- live data, tasks and money come from data.json, regenerated by a scheduled GitHub Action ---- */
let liveData={calendarConnected:false, todoConnected:false, asOf:'', items:{}};
let money={asOf:'', lastMonth:{label:'', income:0, spent:0}, thisMonth:{label:'', income:0, spent:0}, readyToAssign:0, note:''};
let tasks={asOf:'', groups:[]};
let generatedAt=null;

function money$(n){return (n<0?'-$':'$')+Math.abs(n).toLocaleString('en-US',{minimumFractionDigits:2,maximumFractionDigits:2});}

const el=id=>document.getElementById(id);
let view='today';

function today(){
  const parts=new Intl.DateTimeFormat('en-US',{timeZone:'America/Chicago',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(new Date());
  const p=Object.fromEntries(parts.map(x=>[x.type,x.value]));
  return new Date(`${p.year}-${p.month}-${p.day}T12:00:00Z`);
}

function renderMoney(){
  const net=money.lastMonth.income-money.lastMonth.spent;
  const thisNet=money.thisMonth.income-money.thisMonth.spent;
  const hasThisMonth=(money.thisMonth.income||money.thisMonth.spent);
  const rows=[
    ...(hasThisMonth ? [
      [`${money.thisMonth.label} so far — received`, money$(money.thisMonth.income), ''],
      [`${money.thisMonth.label} so far — spent`, money$(money.thisMonth.spent), ''],
      [`${money.thisMonth.label} so far — net`, (thisNet>=0?'+':'')+money$(thisNet), thisNet<0?'warn':'good'],
    ] : []),
    [`${money.lastMonth.label} (final) — received`, money$(money.lastMonth.income), ''],
    [`${money.lastMonth.label} (final) — spent`, money$(money.lastMonth.spent), ''],
    [`${money.lastMonth.label} (final) — net`, (net>=0?'+':'')+money$(net), net<0?'warn':'good'],
    ['Unassigned, ready to budget today', money$(money.readyToAssign), 'good']
  ];
  const rowsEl=document.createElement('div');
  rows.forEach(([label,val,cls])=>{
    const r=document.createElement('div'); r.className='stat-row'+(cls?' '+cls:'');
    const l=document.createElement('span'); l.textContent=label;
    const b=document.createElement('b'); b.textContent=val;
    r.append(l,b); rowsEl.appendChild(r);
  });
  const note=document.createElement('p'); note.className='sub'; note.style.margin='10px 0 0'; note.textContent=money.note+(money.asOf?' Synced '+money.asOf+'.':'');
  el('moneyBody').replaceChildren(rowsEl, note);
}

function render(){
  const d=today();
  if(view==='tomorrow') d.setUTCDate(d.getUTCDate()+1);
  const monthly=view==='month', moneyView=view==='money', daily=view==='today'||view==='tomorrow';
  el('daily').hidden=!daily; el('month').hidden=!monthly; el('money').hidden=!moneyView;
  document.querySelectorAll('[data-view]').forEach(b=>b.setAttribute('aria-pressed',String(view===b.dataset.view)));

  renderMoney(); // independent of which tab is showing; cheap, keeps state current if viewer switches

  if(moneyView){ el('connStatus').textContent=liveData.calendarConnected?'Calendar live · '+liveData.asOf:'Not connected'; el('connStatus').className=liveData.calendarConnected?'pill live':'pill'; return; }

  el('date').textContent=new Intl.DateTimeFormat('en-US',{timeZone:'UTC',...(monthly?{month:'long',year:'numeric'}:{weekday:'long',month:'short',day:'numeric'})}).format(d);
  el('label').textContent=monthly?'YOUR MONTHLY GUIDE':view.toUpperCase()+' · CENTRAL TIME';

  const p=plan(d);
  el('action').textContent=p[0]; el('step').textContent=p[1]; el('slot').textContent=p[2];
  el('duration').textContent=p[3]; el('alternative').textContent=p[4];
  el('origin').textContent=p[5];

  const weekday=d.getUTCDay();
  const rows=(weekday>0&&weekday<6)
    ? [['7–3:30','Work + 45-min commute each way'],['4:30–7:45','Baby care, dinner & shower'],['8 p.m.',p[0]],['9 p.m.','Time with Claudia'],['9:30 p.m.','Bed']]
    : [['Morning',weekday===0?'Church':'Family / park'],['Afternoon','Family / flexible time'],['9 p.m.','Time with Claudia'],['9:30 p.m.','Bed']];
  el('timeline').replaceChildren(...rows.map(([t,s])=>{
    const li=document.createElement('li'),time=document.createElement('time'),span=document.createElement('span');
    time.textContent=t; span.textContent=s; li.append(time,span); return li;
  }));

  if(liveData.calendarConnected){
    el('connStatus').textContent='Calendar live · '+liveData.asOf;
    el('connStatus').className='pill live';
  } else {
    el('connStatus').textContent='Not connected';
    el('connStatus').className='pill';
  }

  const key=d.toISOString().slice(0,10);
  const items=liveData.items[key];
  const todoNote=liveData.todoConnected?'':`<div class="howto" style="margin-top:10px">Microsoft To&nbsp;Do isn't connected yet, so task highlights aren't shown here.</div>`;
  if(!monthly){
    if(!liveData.calendarConnected){
      el('calDot').className='dot';
      el('liveBody').innerHTML=`<p style="margin:0;font-size:.88rem">Google Calendar isn't connected to this dashboard yet, so no live appointments are shown here — showing a made-up agenda would be worse than showing none.</p>
        <div class="howto">Waiting on the scheduled refresh to connect it.</div>${todoNote}`;
    } else if(items === undefined){
      el('calDot').className='dot warn';
      el('liveBody').innerHTML=`<p style="margin:0;font-size:.88rem">Calendar is connected, but this date hasn't been checked yet.</p>${todoNote}`;
    } else if(items.length===0){
      el('calDot').className='dot ok';
      el('liveBody').innerHTML=`<p style="margin:0;font-size:.88rem">Checked — nothing beyond your standing schedule.</p>${todoNote}`;
    } else {
      el('calDot').className='dot ok';
      const list=document.createElement('ul'); list.style.margin='0'; list.style.paddingLeft='18px'; list.style.fontSize='.88rem';
      items.forEach(it=>{const li=document.createElement('li'); li.style.marginBottom='4px'; li.textContent=(it.time?it.time+' — ':'')+it.text; list.appendChild(li);});
      el('liveBody').replaceChildren(list);
      if(todoNote) el('liveBody').insertAdjacentHTML('beforeend', todoNote);
    }
  }

  if(!monthly){
    // Tasks card
    if(!tasks.groups.length){
      el('taskDot').className='dot ok';
      el('taskBody').innerHTML='<p style="margin:0;font-size:.88rem">Checked — no open tasks outside your routines.</p>';
    } else {
      el('taskDot').className=tasks.groups.some(g=>g.items.some(i=>i.overdue))?'dot warn':'dot ok';
      const wrap=document.createElement('div');
      tasks.groups.forEach(g=>{
        const div=document.createElement('div'); div.className='taskgroup';
        const b=document.createElement('b'); b.textContent=g.list;
        const ul=document.createElement('ul');
        g.items.forEach(it=>{
          const li=document.createElement('li');
          if(it.overdue) li.className='overdue';
          li.textContent=it.text+(it.due?' (due '+it.due+')':'')+(it.overdue?' — overdue':'');
          ul.appendChild(li);
        });
        div.append(b,ul); wrap.appendChild(div);
      });
      const note=document.createElement('p'); note.className='sub'; note.style.margin='4px 0 0'; note.textContent='Routine checklists (Household Routines, Trading Development) not shown here.'+(tasks.asOf?' Synced '+tasks.asOf+'.':'');
      el('taskBody').replaceChildren(wrap, note);
    }
  }

  if(monthly){
    el('windows').replaceChildren(...routines.map((r,i)=>{
      const a=document.createElement('article'); a.className='window'+(i===windowIndex(d.getUTCDate())?' active':'');
      const b=document.createElement('b'),div=document.createElement('div'),h=document.createElement('h4'),pp=document.createElement('p');
      b.textContent=r[0]; h.textContent=r[1]; pp.textContent=r[2]; div.append(h,pp); a.append(b,div); return a;
    }));
  }
}

document.querySelectorAll('[data-view]').forEach(b=>b.addEventListener('click',()=>{view=b.dataset.view; render();}));

function renderFooter(){
  const generatedLabel=generatedAt
    ? new Intl.DateTimeFormat('en-US',{timeZone:'America/Chicago',dateStyle:'medium',timeStyle:'short'}).format(new Date(generatedAt))+' Central'
    : 'unknown';
  el('footer').textContent='Data refreshed '+generatedLabel+' by a scheduled GitHub Action. Weekly rhythm and monthly windows are standing rules and stay accurate on their own.';
}

fetch('./data.json', {cache:'no-store'})
  .then(r=>r.ok?r.json():Promise.reject(r.status))
  .then(d=>{
    generatedAt=d.generatedAt||null;
    if(d.liveData) liveData=d.liveData;
    if(d.money) money=d.money;
    if(d.tasks) tasks=d.tasks;
  })
  .catch(()=>{ /* keep defaults — render() still shows something honest */ })
  .finally(()=>{ render(); renderFooter(); });
